const {
  createEnvironment,
  getEnvironmentById,
  listEnvironmentsByUser,
  updateEnvironment,
  deleteEnvironment,
  setDefaultEnvironment,
  createEnvironmentLog,
  cloneEnvironment,
} = require("../models/environment.model");
const { provisionAutomatedSandbox } = require("../services/testDataService");
const SuiteService = require("../services/suitesService");
const { sendResponse, sendError } = require("../utils/response");

function isUnsafeUrl(url) {
  if (!url) return false;
  const lower = String(url).toLowerCase();
  return lower.includes("prod") || lower.includes("production") || lower.includes("live");
}

class EnvironmentController {
  static async create(req, res) {
    try {
      const userId = req.user?.id || req.body.user_id;
      const { environment_type, base_url, suite_id } = req.body;
      if (!suite_id) {
        return sendError(res, 400, "suite_id is required");
      }
      if (suite_id) {
        const suite = await SuiteService.getTestSuiteById(userId, suite_id);
        if (!suite) return sendError(res, 400, "suite_id is invalid or not owned by user");
      }

      if (isUnsafeUrl(base_url)) {
        return sendError(res, 400, "Refusing to use potential production URL in sandbox");
      }

      if (req.body.variables && typeof req.body.variables !== "object") {
        return sendError(res, 400, "variables must be a JSON object");
      }

      let payload = { ...req.body, user_id: userId, created_by: userId };

      if (environment_type === "automated") {
        const provision = await provisionAutomatedSandbox(userId, { id: "env" });
        payload.base_url = provision.base_url;
        payload.auth_config = provision.auth_config;
        payload.variables = { ...(req.body.variables || {}), autogenerated: true };
      }

      const env = await createEnvironment(payload);
      await createEnvironmentLog({
        environment_id: env.id,
        user_id: userId,
        action: "created",
        details: { environment_type: env.environment_type },
      });

      return sendResponse(res, 201, "Environment created", env);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to create environment");
    }
  }

  static async listMine(req, res) {
    try {
      const userId = req.user.id;
      const suiteId = req.query.suite_id;
      if (suiteId) {
        const suite = await SuiteService.getTestSuiteById(userId, suiteId);
        if (!suite) return sendError(res, 400, "suite_id is invalid or not owned by user");
      }
      const envs = await listEnvironmentsByUser(userId, suiteId || null);
      return sendResponse(res, 200, "Environments retrieved", envs);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to list environments");
    }
  }

  static async getOne(req, res) {
    try {
      const env = await getEnvironmentById(req.params.id);
      if (!env) return sendError(res, 404, "Environment not found");
      if (env.user_id !== req.user.id) return sendError(res, 403, "Forbidden");
      return sendResponse(res, 200, "Environment retrieved", env);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to get environment");
    }
  }

  static async updateOne(req, res) {
    try {
      const userId = req.user.id;
      if (isUnsafeUrl(req.body.base_url)) {
        return sendError(res, 400, "Refusing to use potential production URL in sandbox");
      }

      if (req.body.variables && typeof req.body.variables !== "object") {
        return sendError(res, 400, "variables must be a JSON object");
      }

      if (req.body.suite_id) {
        const suite = await SuiteService.getTestSuiteById(userId, req.body.suite_id);
        if (!suite) return sendError(res, 400, "suite_id is invalid or not owned by user");
      }
      const existing = await getEnvironmentById(req.params.id);
      if (!existing) return sendError(res, 404, "Environment not found");
      if (existing.user_id !== userId) return sendError(res, 403, "Forbidden");

      const env = await updateEnvironment(req.params.id, req.body);
      await createEnvironmentLog({
        environment_id: env.id,
        user_id: userId,
        action: "updated",
        details: { changes: req.body },
      });

      return sendResponse(res, 200, "Environment updated", env);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to update environment");
    }
  }

  static async remove(req, res) {
    try {
      const userId = req.user.id;
      const existing = await getEnvironmentById(req.params.id);
      if (!existing) return sendError(res, 404, "Environment not found");
      if (existing.user_id !== userId) return sendError(res, 403, "Forbidden");

      await createEnvironmentLog({
        environment_id: Number(req.params.id),
        user_id: userId,
        action: "deleted",
      });

      await deleteEnvironment(req.params.id);

      return sendResponse(res, 200, "Environment deleted", { deleted: true });
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to delete environment");
    }
  }

  static async setDefault(req, res) {
    try {
      const userId = req.user.id;
      const envCheck = await getEnvironmentById(req.params.id);
      if (!envCheck) return sendError(res, 404, "Environment not found");
      if (envCheck.user_id !== userId) return sendError(res, 403, "Forbidden");
      const env = await setDefaultEnvironment(userId, req.params.id);

      await createEnvironmentLog({
        environment_id: env.id,
        user_id: userId,
        action: "set_default",
      });

      return sendResponse(res, 200, "Default environment set", env);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to set default environment");
    }
  }

  static async clone(req, res) {
    try {
      const userId = req.user.id;
      const cloned = await cloneEnvironment(req.params.id, userId);

      if (!cloned) return sendError(res, 404, "Environment not found");

      await createEnvironmentLog({
        environment_id: cloned.id,
        user_id: userId,
        action: "cloned",
        details: { source_id: req.params.id },
      });

      return sendResponse(res, 201, "Environment cloned", cloned);
    } catch (err) {
      return sendError(res, 400, err.message || "Failed to clone environment");
    }
  }
}

module.exports = EnvironmentController;
